/**
 * VideoMind AI - Document Export Engine & Voice Text-to-Speech Reader
 */

class ExportEngine {
  static copyToClipboard(text, label = 'Content') {
    if (!text) {
      AnimationEngine.showToast('Nothing to copy.', 'error');
      return;
    }
    navigator.clipboard.writeText(text).then(() => {
      AnimationEngine.showToast(`${label} copied to clipboard!`, 'success');
    }).catch(err => {
      console.error('Copy error:', err);
      AnimationEngine.showToast('Failed to copy text.', 'error');
    });
  }

  static downloadFile(filename, textContent, contentType = 'text/plain') {
    const element = document.createElement('a');
    const file = new Blob([textContent], { type: contentType });
    element.href = URL.createObjectURL(file);
    element.download = filename;
    document.body.appendChild(element);
    element.click();
    document.body.removeChild(element);
    AnimationEngine.showToast(`Downloaded ${filename}`, 'success');
  }

  static exportMarkdown(title, content) {
    const mdHeader = `# ${title}\n*Generated by VideoMind AI*\n\n---\n\n`;
    this.downloadFile(`${title.replace(/[^a-z0-9]/gi, '_').toLowerCase()}_summary.md`, mdHeader + content, 'text/markdown');
  }

  static exportTXT(title, content) {
    const txtHeader = `${title}\nGenerated by VideoMind AI\n========================\n\n`;
    this.downloadFile(`${title.replace(/[^a-z0-9]/gi, '_').toLowerCase()}_summary.txt`, txtHeader + content, 'text/plain');
  }

  static exportPDF(title, content) {
    const printWin = window.open('', '_blank');
    printWin.document.write(`
      <!DOCTYPE html>
      <html>
      <head>
        <title>${title} - VideoMind AI Export</title>
        <style>
          body { font-family: system-ui, -apple-system, sans-serif; line-height: 1.6; padding: 2rem; color: #111; }
          h1 { color: #0080FF; border-bottom: 2px solid #eee; padding-bottom: 0.5rem; }
          .footer { margin-top: 3rem; font-size: 0.85rem; color: #666; border-top: 1px solid #eee; padding-top: 1rem; }
        </style>
      </head>
      <body>
        <h1>${title}</h1>
        <div>${content.replace(/\n/g, '<br>')}</div>
        <div class="footer">Exported from VideoMind AI Platform • ${new Date().toLocaleDateString()}</div>
        <script>
          window.onload = function() { window.print(); }
        </script>
      </body>
      </html>
    `);
    printWin.document.close();
  }
}

class VoiceReader {
  constructor() {
    this.synth = window.speechSynthesis;
    this.speaking = false;
    this.utterance = null;
  }

  speak(text, onEndCallback = null) {
    if (!this.synth) {
      AnimationEngine.showToast('Text-to-Speech is not supported in this browser.', 'error');
      return;
    }

    if (this.synth.speaking) {
      this.synth.cancel();
    }

    if (!text || text.trim().length === 0) return;

    const cleanText = text
      .replace(/#+/g, '')
      .replace(/\*+/g, '')
      .replace(/\[[0-9:]+\]/g, '')
      .replace(/```[\s\S]*?```/g, 'Code block omitted.');

    this.utterance = new SpeechSynthesisUtterance(cleanText);
    const speed = appManager.settings.voiceSpeed || 1.0;
    this.utterance.rate = speed;

    this.utterance.onend = () => {
      this.speaking = false;
      if (onEndCallback) onEndCallback();
    };

    this.speaking = true;
    this.synth.speak(this.utterance);
    AnimationEngine.showToast('🔊 Reading summary aloud...', 'info');
  }

  stop() {
    if (this.synth && this.synth.speaking) {
      this.synth.cancel();
      this.speaking = false;
      AnimationEngine.showToast('Audio reading stopped.', 'info');
    }
  }
}

window.ExportEngine = ExportEngine;
window.voiceReader = new VoiceReader();
